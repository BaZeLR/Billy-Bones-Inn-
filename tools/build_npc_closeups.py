#!/usr/bin/env python3
"""Export registered close-ups and dialogue crops without rebuilding base art."""

import argparse
import hashlib
import io
import json
from pathlib import Path
import re

from PIL import Image

from build_npc_sprite_library import ROOT, NAMES, atomic_write, clean_alpha, keep_subject


OUTPUT = ROOT / "game/images/npc_closeups/v1"
RPY = ROOT / "game/Utilities/General/NPC/NPCSpriteCloseups.rpy"


def build(source_map_path):
    records = json.loads(source_map_path.read_text(encoding="utf-8"))["portraits"]
    if not records:
        raise ValueError("No close-up sources provided")
    entries, seen, cameras = [], set(), {}
    for record in records:
        npc, state = record["npc_id"], record["state"]
        if npc not in NAMES or not re.fullmatch(r"[a-z][a-z0-9_]*", state):
            raise ValueError("Invalid NPC or expression identifier")
        if (npc, state) in seen:
            raise ValueError("Duplicate close-up expression")
        seen.add((npc, state))
        source = Path(record["source"])
        if not source.is_absolute():
            source = source_map_path.parent / source
        with Image.open(source) as original:
            size = original.size
            cleaned = Image.fromarray(keep_subject(clean_alpha(original)))
        boxes = {kind: record[f"{kind}_source_box"] for kind in ("portrait", "dialogue")}
        camera = (size, json.dumps(boxes, sort_keys=True))
        group = (npc, record.get("camera_group", "default"))
        if group in cameras and cameras[group] != camera:
            raise ValueError("Expressions in a camera group require the same canvas and crops")
        cameras[group] = camera
        for kind, dimensions, baseline, padding in (
            ("portrait", (640, 800), 768, 32), ("dialogue", (320, 320), 300, 32)
        ):
            x0, y0, x1, y1 = boxes[kind]
            if not (0 <= x0 < x1 <= size[0] and 0 <= y0 < y1 <= size[1]):
                raise ValueError("Crop lies outside its source")
            tile = cleaned.crop((x0, y0, x1, y1))
            scale = min((dimensions[0] - padding) / tile.width,
                        (dimensions[1] - 2 * padding) / tile.height)
            tile = tile.resize((round(tile.width * scale), round(tile.height * scale)), Image.Resampling.LANCZOS)
            tile = Image.fromarray(clean_alpha(tile))
            canvas = Image.new("RGBA", dimensions)
            placement = [(dimensions[0] - tile.width) // 2, baseline - tile.height]
            canvas.alpha_composite(tile, tuple(placement))
            suffix = "" if kind == "portrait" else "_dialogue"
            path = OUTPUT / npc / f"{npc}_closeup_{state}{suffix}.png"
            encoded = io.BytesIO()
            canvas.save(encoded, "PNG", optimize=True)
            payload = encoded.getvalue()
            atomic_write(path, payload)
            entries.append({
                "npc_id": npc, "state": state, "kind": kind,
                "image_name": f"npc_{npc} closeup {state}" if kind == "portrait" else f"side npcface_{npc} closeup_{state}",
                "dialogue_attribute": f"closeup_{state}",
                "path": path.relative_to(ROOT / "game").as_posix(),
                "canvas": list(dimensions), "visible_bounds": list(canvas.getbbox()),
                "source_box": boxes[kind], "placement": placement, "scale": scale,
                "sha256": hashlib.sha256(payload).hexdigest(),
                "source": {"filename": source.name, "size": list(size), "sha256": hashlib.sha256(source.read_bytes()).hexdigest()},
            })
    manifest = {"version": 1, "collection": "npc_closeups", "requires": "npc_sprites/v1",
                "complete": True, "sprites": entries,
                "notes": ["Full portraits and dialogue crops share a camera per expression set.",
                          "Existing npc_*_voice aliases and npcface_* side-image tags are reused."]}
    atomic_write(OUTPUT / "manifest.json", (json.dumps(manifest, indent=2) + "\n").encode())
    lines = ["# Generated by tools/build_npc_closeups.py.", "# Native images and existing dialogue aliases; no NPC/story state.", ""]
    for entry in entries:
        if entry["kind"] == "portrait":
            lines.append(f'image {entry["image_name"]} = "{entry["path"]}"')
        else:
            lines.append(f'image {entry["image_name"]} = Transform("{entry["path"]}", xysize=(220, 220), fit="contain")')
    lines += ["", "# Existing media-panel overlay canvas and placement."]
    for entry in entries:
        if entry["kind"] == "portrait":
            name = f'npc_overlay_{entry["npc_id"]}_closeup_{entry["state"]}'
            lines.append(f'image {name} = Composite((1536, 1024), (448, 224), "{entry["path"]}")')
    atomic_write(RPY, ("\n".join(lines) + "\n").encode())
    print(f"Prepared {len(entries)} close-up/dialogue PNGs.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-map", required=True, type=Path)
    build(parser.parse_args().source_map.resolve())
