#!/usr/bin/env python3
"""Prepare independent card-game cutouts without rebuilding the base library.

Usage: python tools/build_npc_card_game_sprites.py --source-map SOURCES.json
The map contains a sprites list with npc_id, state, source and max_height.
Relative source paths resolve against the map file. Offline dependencies:
Pillow, numpy and scipy. Runtime Ren'Py needs only the exported PNGs.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
from pathlib import Path
import re

from PIL import Image

from build_npc_sprite_library import NAMES, ROOT, atomic_write, clean_alpha, keep_subject

OUTPUT = ROOT / "game/images/npc_card_game/v1"
RPY = ROOT / "game/Utilities/General/NPC/NPCSpriteCardGame.rpy"


def build(source_map_path):
    records = json.loads(source_map_path.read_text(encoding="utf-8"))["sprites"]
    if not records:
        raise ValueError("No card-game sources provided")
    entries, seen = [], set()
    for record in records:
        npc, state = record["npc_id"], record["state"]
        if npc not in NAMES or not re.fullmatch(r"[a-z][a-z0-9_]*", state):
            raise ValueError("Invalid character or pose id")
        if (npc, state) in seen:
            raise ValueError("Duplicate card-game pose")
        seen.add((npc, state))
        maximum_height = int(record.get("max_height", 736))
        if not 32 <= maximum_height <= 736:
            raise ValueError("Pose height must be between 32 and 736 pixels")
        source = Path(record["source"])
        if not source.is_absolute():
            source = source_map_path.parent / source
        with Image.open(source) as original:
            source_size = list(original.size)
            sprite = Image.fromarray(keep_subject(clean_alpha(original)))
        sprite = sprite.crop(sprite.getbbox())
        scale = min(1.35, 608 / sprite.width, maximum_height / sprite.height)
        sprite = sprite.resize((max(1, round(sprite.width * scale)),
                                max(1, round(sprite.height * scale))), Image.Resampling.LANCZOS)
        sprite = Image.fromarray(clean_alpha(sprite))
        canvas = Image.new("RGBA", (640, 800))
        canvas.alpha_composite(sprite, ((640 - sprite.width) // 2, 768 - sprite.height))
        encoded = io.BytesIO()
        canvas.save(encoded, format="PNG", optimize=True)
        payload = encoded.getvalue()
        path = OUTPUT / npc / (npc + "_cards_" + state + ".png")
        atomic_write(path, payload)
        entries.append({
            "npc_id": npc, "display_name": NAMES[npc], "group": "cards", "state": state,
            "image_name": "npc_{} cards {}".format(npc, state),
            "overlay_name": "npc_overlay_{}_cards_{}".format(npc, state),
            "path": path.relative_to(ROOT / "game").as_posix(),
            "canvas": [640, 800], "baseline": 768, "max_height": maximum_height,
            "visible_bounds": list(canvas.getbbox()), "scale": scale,
            "sha256": hashlib.sha256(payload).hexdigest(),
            "source": {"filename": source.name, "size": source_size,
                       "sha256": hashlib.sha256(source.read_bytes()).hexdigest()},
        })
    manifest = {"version": 1, "collection": "card_game", "complete": True,
                "asset_kind": "individual complete static RGBA sprites",
                "requires": "npc_sprites/v1", "sprites": entries,
                "notes": ["Amanda extension: tease, forfeit and challenge.",
                          "Cards show decorative backs; ranks belong to game state/UI.",
                          "Furniture-free cutouts; place against the scene's seating.",
                          "No card rules, wardrobe layers or gameplay state are added."]}
    atomic_write(OUTPUT / "manifest.json", (json.dumps(manifest, indent=2) + "\n").encode())
    lines = ["# Generated by tools/build_npc_card_game_sprites.py.",
             "# Static cutouts and existing media-panel overlays; no card-game state.", ""]
    for entry in entries:
        lines.append('image {} = "{}"'.format(entry["image_name"], entry["path"]))
    lines += ["", "# Same 1536x1024 BGIMAGE canvas and body placement as NPCSpriteLibrary."]
    for entry in entries:
        lines.append('image {} = Composite((1536, 1024), (448, 224), "{}")'.format(
            entry["overlay_name"], entry["path"]))
    atomic_write(RPY, ("\n".join(lines) + "\n").encode())
    print("Prepared {} card-game RGBA sprites.".format(len(entries)))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-map", required=True, type=Path)
    arguments = parser.parse_args()
    build(arguments.source_map.resolve())
